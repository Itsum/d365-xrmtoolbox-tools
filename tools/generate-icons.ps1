# Generates the tool logos:
#  - PluginIcons.cs in both projects (32x32 small / 80x80 big image for the XrmToolBox tool list)
#  - docs/icons/*.png (128x128) – referenced by the NuGet iconUrl
# Run: powershell -ExecutionPolicy Bypass -File tools\generate-icons.ps1
Add-Type -AssemblyName System.Drawing

function New-RoundedPath([float]$x, [float]$y, [float]$w, [float]$h, [float]$r) {
    $p = New-Object System.Drawing.Drawing2D.GraphicsPath
    $p.AddArc($x, $y, $r, $r, 180, 90)
    $p.AddArc($x + $w - $r, $y, $r, $r, 270, 90)
    $p.AddArc($x + $w - $r, $y + $h - $r, $r, $r, 0, 90)
    $p.AddArc($x, $y + $h - $r, $r, $r, 90, 90)
    $p.CloseFigure()
    $p
}

function Draw-Audit($g, [int]$s) {
    $blue = [System.Drawing.Color]::FromArgb(0, 120, 212)
    $g.FillPath((New-Object System.Drawing.SolidBrush $blue), (New-RoundedPath 0 0 ($s - 1) ($s - 1) ($s * 0.24)))
    # shield
    $shield = New-Object System.Drawing.Drawing2D.GraphicsPath
    $cx = $s / 2
    $shield.AddLines([System.Drawing.PointF[]]@(
        (New-Object System.Drawing.PointF ($cx), ($s * 0.16)),
        (New-Object System.Drawing.PointF ($s * 0.78), ($s * 0.27)),
        (New-Object System.Drawing.PointF ($s * 0.76), ($s * 0.55))))
    $shield.AddBezier(($s * 0.76), ($s * 0.55), ($s * 0.72), ($s * 0.72), ($s * 0.62), ($s * 0.80), $cx, ($s * 0.86))
    $shield.AddBezier($cx, ($s * 0.86), ($s * 0.38), ($s * 0.80), ($s * 0.28), ($s * 0.72), ($s * 0.24), ($s * 0.55))
    $shield.AddLine(($s * 0.24), ($s * 0.55), ($s * 0.22), ($s * 0.27))
    $shield.CloseFigure()
    $g.FillPath([System.Drawing.Brushes]::White, $shield)
    # check mark
    $pen = New-Object System.Drawing.Pen $blue, ([float]($s * 0.075))
    $pen.StartCap = 'Round'; $pen.EndCap = 'Round'; $pen.LineJoin = 'Round'
    $g.DrawLines($pen, [System.Drawing.PointF[]]@(
        (New-Object System.Drawing.PointF ($s * 0.37), ($s * 0.50)),
        (New-Object System.Drawing.PointF ($s * 0.47), ($s * 0.61)),
        (New-Object System.Drawing.PointF ($s * 0.65), ($s * 0.40))))
}

function Draw-Translation($g, [int]$s) {
    $teal = [System.Drawing.Color]::FromArgb(0, 128, 116)
    $g.FillPath((New-Object System.Drawing.SolidBrush $teal), (New-RoundedPath 0 0 ($s - 1) ($s - 1) ($s * 0.24)))
    $back = New-RoundedPath ($s * 0.40) ($s * 0.38) ($s * 0.46) ($s * 0.40) ($s * 0.12)
    $g.FillPath((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(178, 255, 255, 255))), $back)
    $front = New-RoundedPath ($s * 0.14) ($s * 0.18) ($s * 0.46) ($s * 0.40) ($s * 0.12)
    $g.FillPath([System.Drawing.Brushes]::White, $front)
    $fmt = New-Object System.Drawing.StringFormat
    $fmt.Alignment = 'Center'; $fmt.LineAlignment = 'Center'
    $font = New-Object System.Drawing.Font 'Segoe UI', ([float]($s * 0.27)), ([System.Drawing.FontStyle]::Bold), ([System.Drawing.GraphicsUnit]::Pixel)
    $g.DrawString('A', $font, (New-Object System.Drawing.SolidBrush $teal), (New-Object System.Drawing.RectangleF ($s * 0.14), ($s * 0.18), ($s * 0.46), ($s * 0.40)), $fmt)
    $g.DrawString([string][char]0x00C4, $font, (New-Object System.Drawing.SolidBrush $teal), (New-Object System.Drawing.RectangleF ($s * 0.40), ($s * 0.38), ($s * 0.46), ($s * 0.40)), $fmt)
}

function New-Png([int]$size, $drawer) {
    $bmp = New-Object System.Drawing.Bitmap $size, $size
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $g.TextRenderingHint = 'AntiAliasGridFit'
    $g.Clear([System.Drawing.Color]::Transparent)
    & $drawer $g $size
    $g.Dispose()
    $ms = New-Object System.IO.MemoryStream
    $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    $ms.ToArray()
}

$root = Split-Path $PSScriptRoot -Parent
$utf8 = New-Object Text.UTF8Encoding($false)
New-Item -ItemType Directory -Force (Join-Path $root 'docs\icons') | Out-Null

$targets = @(
    @{ Project = 'D365AuditManager'; Namespace = 'D365Tools.AuditManager'; Drawer = ${function:Draw-Audit}; Png = 'audit-manager.png' },
    @{ Project = 'D365TranslationManager'; Namespace = 'D365Tools.TranslationManager'; Drawer = ${function:Draw-Translation}; Png = 'translation-manager.png' }
)

foreach ($t in $targets) {
    $small = [Convert]::ToBase64String((New-Png 32 $t.Drawer))
    $big = [Convert]::ToBase64String((New-Png 80 $t.Drawer))
    $code = @"
// <auto-generated> by tools/generate-icons.ps1 </auto-generated>
namespace $($t.Namespace)
{
    internal static class PluginIcons
    {
        public const string Small = "$small";
        public const string Big = "$big";
    }
}
"@
    [IO.File]::WriteAllText((Join-Path $root "src\$($t.Project)\PluginIcons.cs"), $code, $utf8)
    [IO.File]::WriteAllBytes((Join-Path $root "docs\icons\$($t.Png)"), (New-Png 128 $t.Drawer))
    Write-Output "Written: $($t.Project)\PluginIcons.cs, docs\icons\$($t.Png)"
}
